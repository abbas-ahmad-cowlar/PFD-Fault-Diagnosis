function delete_default_ports(sys)
    % Remove the default In1/Out1 blocks from a new Subsystem
    try delete_block([sys '/In1']);  catch, end
    try delete_block([sys '/Out1']); catch, end
    try delete_line(sys, 'In1/1', 'Out1/1'); catch, end
end

function add_goto_block(sys, name, tag, pos, srcPort)
    % Add a Goto block and optionally wire a source to it
    blkPath = [sys '/' name];
    add_block('simulink/Signal Routing/Goto', blkPath, ...
        'GotoTag', tag, ...
        'TagVisibility', 'global', ...
        'Position', pos);
    if nargin >= 5 && ~isempty(srcPort)
        add_line(sys, srcPort, [name '/1'], 'autorouting', 'smart');
    end
end

function add_from_block(sys, name, tag, pos)
    % Add a From block with specified tag
    blkPath = [sys '/' name];
    add_block('simulink/Signal Routing/From', blkPath, ...
        'GotoTag', tag, ...
        'Position', pos);
end

